#!/usr/bin/env bash
# Phase 1 of the C++ payload: materialize the pinned conda-forge closure at the
# guest path the sandbox will mount it at.
#
# ── WHY CONDA-FORGE AND NOT A SOURCE BUILD ─────────────────────────────────
# The other three payloads build from pinned source because their source builds
# are minutes. xeus-cpp's is not: it needs LLVM/Clang 21 (xeus-cpp 0.10.0
# requires CppInterOp 1.9.0, whose conda_build_config pins clangdev 21.*), and
# an LLVM build is hours of CPU and tens of gigabytes of intermediate state.
# conda-forge is also how upstream actually ships this kernel — the feedstock at
# github.com/conda-forge/xeus-cpp-feedstock is the distribution, and the
# kernel.json the project installs is generated by that build. Repacking it is
# closer to what upstream tests than any recipe we would invent.
#
# The house rule survives the choice: conda's "explicit" install format is a
# list of URLs each carrying its own checksum, so a locked install is exactly as
# pinned as a checksummed tarball, and nothing is solved at build time.
#
# ── THE BOOTSTRAP GAP, STATED PLAINLY ──────────────────────────────────────
# Producing that lock requires a solve against linux-64 repodata, which requires
# the network and a solver. This script therefore has two modes:
#
#   deploy/cpp-runtime/conda-linux-64.lock exists  → install from it, nothing
#     is solved, every artifact is verified by the checksum in the file.
#   it does not exist                              → refuse, unless
#     CPP_RUNTIME_SOLVE=1, in which case solve from the version pins below and
#     PRINT the resulting lock so it can be committed.
#
# The first cloud build runs the second mode and hands back the lock. Every
# build after the lock is committed runs the first. The gap is one build wide
# and it is visible in the log rather than hidden in a comment.
set -euo pipefail

CPP_RUNTIME_ROOT="${CPP_RUNTIME_ROOT:?CPP_RUNTIME_ROOT is required}"
MICROMAMBA="${MICROMAMBA:?MICROMAMBA is required}"
CPP_RUNTIME_LOCK="${CPP_RUNTIME_LOCK:?CPP_RUNTIME_LOCK is required}"
XEUS_CPP_VERSION="${XEUS_CPP_VERSION:?XEUS_CPP_VERSION is required}"
CPPINTEROP_VERSION="${CPPINTEROP_VERSION:?CPPINTEROP_VERSION is required}"
CPP_LLVM_MAJOR="${CPP_LLVM_MAJOR:?CPP_LLVM_MAJOR is required}"
CPP_RUNTIME_SOLVE="${CPP_RUNTIME_SOLVE:-0}"

MANIFEST_DIR="${CPP_RUNTIME_ROOT}/share/choreograph"
EMITTED_LOCK="${MANIFEST_DIR}/conda-linux-64.lock"

# What the payload has to contain, and why each entry is here rather than
# arriving as somebody else's transitive dependency:
#
#   xeus-cpp        the kernel. Pulls xeus, xeus-zmq, zeromq, libsodium,
#                   openssl, nlohmann_json, pugixml, cpp-argparse, libcurl and
#                   cppinterop as declared runtime dependencies.
#   cppinterop      pinned explicitly even though xeus-cpp requires it, because
#                   this is the package that fixes the LLVM major version and a
#                   silent bump would change every path below.
#   clang-${major}  the clang *resource directory* — lib/clang/21/include, the
#                   builtin headers (stddef.h, stdarg.h, the intrinsics). This
#                   is the one thing the kernel cannot work without and does not
#                   depend on: conda-forge splits it into its own output
#                   (clangdev-feedstock recipe.yaml, `name: clang-${major}`,
#                   files include lib/clang/${major}/*), and neither xeus-cpp
#                   nor cppinterop declares it. Installing xeus-cpp alone
#                   produces a kernel whose kernel.json names a -resource-dir
#                   that does not exist.
#   clangxx         the driver, for the build-time hermeticity probe in phase 2
#                   and for nothing at runtime.
#   gxx_impl_linux-64 + sysroot_linux-64
#                   the C++ standard library headers and the glibc headers.
#                   clang-repl compiles #include <iostream> in the sandbox,
#                   where /usr belongs to whatever host the sandbox runs on and
#                   is not ours. CppInterOp's own answer to this —
#                   DetectSystemCompilerIncludePaths(), which popen()s
#                   `c++ -xc++ -E -v /dev/null` — cannot work there: the sandbox
#                   has PATH=/nonexistent and no compiler. So the headers travel
#                   inside the bundle and phase 2 proves they are the ones used.
CONDA_SPECS=(
	"xeus-cpp==${XEUS_CPP_VERSION}"
	"cppinterop==${CPPINTEROP_VERSION}"
	"clang-${CPP_LLVM_MAJOR}"
	"clangxx==${CPP_LLVM_MAJOR}.*"
	"gxx_impl_linux-64"
	"sysroot_linux-64"
)

mkdir -p "${MANIFEST_DIR%/share/choreograph}"

if [ -f "${CPP_RUNTIME_LOCK}" ]; then
	echo "==> Installing the C++ payload from the committed lock"
	echo "    ${CPP_RUNTIME_LOCK} ($(grep -c '^https\?://' "${CPP_RUNTIME_LOCK}" || true) packages)"
	"${MICROMAMBA}" create --yes --prefix "${CPP_RUNTIME_ROOT}" \
		--platform linux-64 \
		--file "${CPP_RUNTIME_LOCK}"
elif [ "${CPP_RUNTIME_SOLVE}" = "1" ]; then
	echo "==> BOOTSTRAP: no committed lock; solving from pins"
	echo "    This build is not hermetic. Commit the lock printed at the end of"
	echo "    this phase to deploy/cpp-runtime/conda-linux-64.lock and rebuild."
	printf '    spec: %s\n' "${CONDA_SPECS[@]}"
	"${MICROMAMBA}" create --yes --prefix "${CPP_RUNTIME_ROOT}" \
		--platform linux-64 \
		--channel conda-forge \
		--override-channels \
		"${CONDA_SPECS[@]}"
else
	echo "ERROR: ${CPP_RUNTIME_LOCK} does not exist and CPP_RUNTIME_SOLVE is not 1." >&2
	echo "       A hermetic build installs only from a checksummed lock. Rebuild" >&2
	echo "       once with --build-arg CPP_RUNTIME_SOLVE=1 to produce one." >&2
	exit 1
fi

echo "==> Recording the exact closure that was installed"
mkdir -p "${MANIFEST_DIR}"
# --explicit emits one `url#sha256` line per package: the same form this script
# consumes, so the record is directly re-installable rather than descriptive.
"${MICROMAMBA}" env export --explicit --prefix "${CPP_RUNTIME_ROOT}" > "${EMITTED_LOCK}"
echo "    ${EMITTED_LOCK}"
echo "──────── deploy/cpp-runtime/conda-linux-64.lock ────────"
cat "${EMITTED_LOCK}"
echo "────────────────────────────────────────────────────────"

if [ -f "${CPP_RUNTIME_LOCK}" ]; then
	# A lock that installs something other than itself is worse than no lock.
	# Compare the URL sets rather than the files: micromamba's own export
	# normalizes ordering and comment lines.
	INSTALLED_URLS="$(grep -o '^https\?://[^#]*' "${EMITTED_LOCK}" | sort)"
	REQUESTED_URLS="$(grep -o '^https\?://[^#]*' "${CPP_RUNTIME_LOCK}" | sort)"
	if [ "${INSTALLED_URLS}" != "${REQUESTED_URLS}" ]; then
		echo "ERROR: the installed closure does not match the committed lock" >&2
		diff <(printf '%s\n' "${REQUESTED_URLS}") <(printf '%s\n' "${INSTALLED_URLS}") >&2 || true
		exit 1
	fi
	echo "    installed closure matches the committed lock exactly"
fi

echo "==> Installed C++ payload size"
du -sh "${CPP_RUNTIME_ROOT}"
